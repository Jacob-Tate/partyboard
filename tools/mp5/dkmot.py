"""MP5 -> MP4 character motion numbers, for DK (no MP5 motions; include/REL/mp5compat.h mp5ToMp4MotTbl).
Usage: python tools/mp5/dkmot.py <MP4 data dir> <MP5 data dir>   (extracted discs' data/ folders)

Both games' <char>mot.bin hold mostly the same animation files under different numbers. An archive entry
starts with its uncompressed size; an MP5 entry maps to the MP4 entry whose size matches for most of the
seven characters both games have (>= 4 of 7, and no runner-up as good). Entries 0-2 (idle, walk, run, the
c000m1_300-302 of both games) were re-exported in MP5 and keep their numbers."""
import collections, os, struct, sys

CHARS = ['mario', 'luigi', 'peach', 'yoshi', 'wario', 'daisy', 'waluigi']


def sizes(path):
    d = open(path, 'rb').read()
    n = struct.unpack('>I', d[:4])[0]
    return [struct.unpack('>I', d[o:o + 4])[0] for o in struct.unpack('>%dI' % n, d[4:4 + 4 * n])]


m4 = {c: sizes(os.path.join(sys.argv[1], c + 'mot.bin')) for c in CHARS}
m5 = {c: sizes(os.path.join(sys.argv[2], c + 'mot.bin')) for c in CHARS}
tbl = []
for i in range(len(m5['mario'])):
    votes = collections.Counter(j for c in CHARS for j, s in enumerate(m4[c]) if s == m5[c][i])
    best = votes.most_common(2)
    if i < 3:
        tbl.append(i)
    elif best and best[0][1] >= 4 and (len(best) == 1 or best[1][1] < best[0][1]):
        tbl.append(best[0][0])
    else:
        tbl.append(-1)
print('// generated by tools/mp5/dkmot.py: %d of %d mapped' % (sum(x >= 0 for x in tbl), len(tbl)))
print('static const s16 mp5ToMp4MotTbl[%d] = {' % len(tbl))
for k in range(0, len(tbl), 16):
    print('    ' + ', '.join('%d' % x for x in tbl[k:k + 16]) + ',')
print('};')
